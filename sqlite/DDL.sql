

CREATE TABLE IF NOT EXISTS Users (
	userID INTEGER PRIMARY KEY AUTOINCREMENT,
	name TEXT UNIQUE NOT NULL,
	email TEXT UNIQUE NOT NULL,
	userpassword TEXT NOT NULL
);


CREATE TABLE IF NOT EXISTS Books (
	bookID INTEGER PRIMARY KEY AUTOINCREMENT,
	title TEXT NOT NULL,
	description TEXT,
	published TEXT,
	categories TEXT,
	cover TEXT,
	pages INTEGER,
	isbn TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS Shelves (
	shelvesID INTEGER PRIMARY KEY AUTOINCREMENT,
	name TEXT NOT NULL,
	userID INTEGER NOT NULL,
	FOREIGN KEY (userID) REFERENCES Users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Writers (
	writerID INTEGER PRIMARY KEY AUTOINCREMENT,
	name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS Users_Books(
	userID INTEGER NOT NULL,
	bookID INTEGER NOT NULL,
	PRIMARY KEY (userID, bookID),
	FOREIGN KEY (userID) REFERENCES Users(userID) ON DELETE CASCADE,
	FOREIGN KEY (bookID) REFERENCES Books(bookID) ON DELETE CASCADE
);

CREATE TABLE  IF NOT EXISTS Books_Writers (
	bookID INTEGER NOT NULL,
	writerID INTEGER NOT NULL,
	PRIMARY KEY (bookID, writerID),
	FOREIGN KEY (bookID) REFERENCES Books(bookID) ON DELETE CASCADE,
	FOREIGN KEY (writerID) REFERENCES Writers(writerID) ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS Books_Shelves (
	bookID INTEGER NOT NULL,
	shelvesID INTEGER NOT NULL,
	PRIMARY KEY (bookID, shelvesID),
	FOREIGN KEY (bookID) REFERENCES Books(bookID) ON DELETE CASCADE,
	FOREIGN KEY (shelvesID) REFERENCES Shelves(shelvesID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS BookStatus (
	userID INTEGER NOT NULL,
	bookID INTEGER NOT NULL,
	progress INTEGER,
	status TEXT NOT NULL,
	rating INTEGER,
	startReading TEXT,
	endReading TEXT,
	PRIMARY KEY (userID, bookID),
	FOREIGN KEY (bookID) REFERENCES Books(bookID) ON DELETE CASCADE,
	FOREIGN KEY (userID) REFERENCES Users(userID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS Notes (
	notesID INTEGER PRIMARY KEY AUTOINCREMENT,
	text TEXT,
	created TEXT,
	bookID INTEGER NOT NULL,
	userID INTEGER NOT NULL,
	FOREIGN KEY (bookID) REFERENCES Books(bookID) ON DELETE CASCADE
	FOREIGN KEY (userID) REFERENCES Users(userID) ON DELETE CASCADE
);
